/**
 * Bounded file discovery.
 *
 * Every limit here exists because a scanner that reads a hostile or merely huge
 * repository must still finish. Nothing is read that is not (a) inside a caller-named
 * target, (b) inside the scan root after symlink resolution, and (c) under the caps.
 * Skips are reported with a reason so a count is never printed without its caveats.
 */

import { opendir, readFile, realpath, stat } from 'node:fs/promises';
import { basename, extname, isAbsolute, join, relative, resolve, sep } from 'node:path';

/** Extensions we will look inside, mapped to the kind of file they are. */
export const EXTENSIONS = Object.freeze({
  '.html': 'markup',
  '.htm': 'markup',
  '.jsx': 'markup',
  '.tsx': 'markup',
  '.vue': 'markup',
  '.svelte': 'markup',
  '.astro': 'markup',
  '.js': 'script',
  '.mjs': 'script',
  '.cjs': 'script',
  '.ts': 'script',
  '.mts': 'script',
  '.cts': 'script',
  '.css': 'style',
  '.scss': 'style',
  '.less': 'style',
  '.json': 'config',
});

/** Directories never entered. */
export const SKIP_DIRECTORIES = Object.freeze([
  '.git',
  'node_modules',
  'dist',
  'build',
  'out',
  'coverage',
  '.next',
  '.nuxt',
  '.svelte-kit',
  '.turbo',
  '.cache',
  'vendor',
  'target',
  '.venv',
  'venv',
  '__pycache__',
  '.s-eidos',
]);

/** Files whose content is never content we should judge. */
const LOCKFILES = Object.freeze([
  'package-lock.json',
  'pnpm-lock.yaml',
  'yarn.lock',
  'bun.lockb',
  'composer.lock',
  'Cargo.lock',
]);

/** Generated-file markers, matched against the first lines. */
const GENERATED_MARKERS = Object.freeze([
  '@generated',
  'do not edit',
  'autogenerated',
  'auto-generated',
  'code generated by',
  'this file was generated',
]);

export const DEFAULT_LIMITS = Object.freeze({
  maxFiles: 500,
  maxFileBytes: 1024 * 1024,
  maxTotalBytes: 16 * 1024 * 1024,
  maxDepth: 24,
});

/**
 * @typedef {{ path: string, abs: string, kind: string, language: string, bytes: number }} ScannedFile
 * @typedef {{ path: string, reason: string }} SkippedPath
 */

/**
 * @param {string} filePath
 * @param {number} [probeBytes]
 * @returns {Promise<boolean>} true when the file looks binary
 */
async function looksBinary(filePath) {
  const handle = await readFile(filePath);
  const probe = handle.subarray(0, 8000);
  for (const byte of probe) if (byte === 0) return true;
  return false;
}

/**
 * @param {string} text
 * @returns {boolean}
 */
function looksGenerated(text) {
  const head = text.slice(0, 600).toLowerCase();
  return GENERATED_MARKERS.some((marker) => head.includes(marker));
}

/**
 * @param {string} kind markup | script | style | config
 * @param {string} text
 * @returns {boolean}
 */
function isProbablyMinifiedByExtension(kind, text) {
  if (kind !== 'script' && kind !== 'style') return false;
  const lines = text.split('\n');
  let longest = 0;
  for (const line of lines) if (line.length > longest) longest = line.length;
  if (longest > 800) return true;
  // Several very long lines and almost no short ones: machine output, not hand-written code.
  const average = text.length / Math.max(lines.length, 1);
  return longest > 500 && average > 200;
}

/**
 * Walk a set of explicit targets and return the files that may be scanned.
 *
 * @param {object} request
 * @param {string} request.root absolute scan root; every target must resolve inside it
 * @param {string[]} request.targets explicit file or directory paths (relative to root, or absolute inside it)
 * @param {Partial<typeof DEFAULT_LIMITS>} [request.limits]
 * @returns {Promise<{ ok: true, files: ScannedFile[], skipped: SkippedPath[], truncated: boolean }
 *   | { ok: false, error: { code: string, message: string } }>}
 */
export async function collectFiles({ root, targets, limits = {} }) {
  const bounds = { ...DEFAULT_LIMITS, ...limits };

  if (!Array.isArray(targets) || targets.length === 0) {
    return {
      ok: false,
      error: {
        code: 'no-targets',
        message: 'Name at least one file or directory. S-Eidos never scans the working directory implicitly.',
      },
    };
  }

  let realRoot;
  try {
    realRoot = await realpath(root);
  } catch {
    return { ok: false, error: { code: 'root-missing', message: `Scan root does not exist: ${root}` } };
  }

  /** @type {ScannedFile[]} */
  const files = [];
  /** @type {SkippedPath[]} */
  const skipped = [];
  let totalBytes = 0;
  let truncated = false;

  const skip = (path, reason) => {
    skipped.push({ path: path.split(sep).join('/'), reason });
  };

  const seenDirectories = new Set();

  /**
   * @param {string} filePath absolute path of a candidate file
   * @param {string} displayPath path relative to the root, for output
   */
  async function considerFile(filePath, displayPath) {
    if (files.length >= bounds.maxFiles) {
      truncated = true;
      return;
    }

    const base = basename(filePath);
    if (LOCKFILES.includes(base)) return skip(displayPath, 'lockfile');

    const extension = extname(filePath).toLowerCase();
    const kind = EXTENSIONS[extension];
    if (kind === undefined) return skip(displayPath, 'extension');

    let info;
    try {
      info = await stat(filePath);
    } catch {
      return skip(displayPath, 'unreadable');
    }
    if (!info.isFile()) return skip(displayPath, 'not-a-file');
    if (info.size === 0) return skip(displayPath, 'empty');
    if (info.size > bounds.maxFileBytes) return skip(displayPath, 'too-large');
    if (totalBytes + info.size > bounds.maxTotalBytes) {
      truncated = true;
      return skip(displayPath, 'total-budget');
    }

    let text;
    try {
      if (await looksBinary(filePath)) return skip(displayPath, 'binary');
      text = await readFile(filePath, 'utf8');
    } catch {
      return skip(displayPath, 'unreadable');
    }

    if (looksGenerated(text)) return skip(displayPath, 'generated');
    if (isProbablyMinifiedByExtension(kind, text)) return skip(displayPath, 'minified');

    totalBytes += info.size;
    files.push({
      path: displayPath.split(sep).join('/'),
      abs: filePath,
      kind,
      language: extension.slice(1),
      bytes: info.size,
    });
  }

  /**
   * @param {string} directoryPath
   * @param {number} depth
   */
  async function walk(directoryPath, depth) {
    if (depth > bounds.maxDepth) {
      skip(relative(realRoot, directoryPath) || '.', 'depth');
      return;
    }

    let realDirectory;
    try {
      realDirectory = await realpath(directoryPath);
    } catch {
      skip(relative(realRoot, directoryPath) || '.', 'unreadable');
      return;
    }

    // Containment: a symlinked directory must not lead outside the root.
    const relativeReal = relative(realRoot, realDirectory);
    if (relativeReal.startsWith('..') || isAbsolute(relativeReal)) {
      skip(relative(realRoot, directoryPath) || '.', 'symlink-escape');
      return;
    }
    if (seenDirectories.has(realDirectory)) {
      skip(relative(realRoot, directoryPath) || '.', 'cycle');
      return;
    }
    seenDirectories.add(realDirectory);

    let directory;
    try {
      directory = await opendir(realDirectory);
    } catch {
      skip(relative(realRoot, directoryPath) || '.', 'unreadable');
      return;
    }

    /** @type {string[]} */
    const names = [];
    for await (const entry of directory) names.push(entry.name);
    names.sort();

    for (const name of names) {
      if (files.length >= bounds.maxFiles) {
        truncated = true;
        return;
      }
      const childPath = join(realDirectory, name);
      let info;
      try {
        info = await stat(childPath);
      } catch {
        skip(relative(realRoot, childPath), 'unreadable');
        continue;
      }

      if (info.isDirectory()) {
        if (SKIP_DIRECTORIES.includes(name) || name.startsWith('.')) {
          skip(relative(realRoot, childPath), name.startsWith('.') ? 'dot-directory' : 'skipped-directory');
          continue;
        }
        await walk(childPath, depth + 1);
        continue;
      }

      if (info.isSymbolicLink()) {
        // stat() follows links, so this branch is only reached for broken links.
        skip(relative(realRoot, childPath), 'broken-symlink');
        continue;
      }

      await considerFile(childPath, relative(realRoot, childPath));
    }
  }

  for (const target of targets) {
    const requested = isAbsolute(target) ? target : resolve(realRoot, target);
    const relativeRequested = relative(realRoot, requested);
    if (relativeRequested.startsWith('..') || isAbsolute(relativeRequested)) {
      return {
        ok: false,
        error: { code: 'target-outside', message: `Target is outside the scan root: ${target}` },
      };
    }

    let info;
    try {
      info = await stat(requested);
    } catch {
      return { ok: false, error: { code: 'target-missing', message: `Target does not exist: ${target}` } };
    }

    if (info.isDirectory()) {
      await walk(requested, 0);
    } else {
      await considerFile(await realpath(requested), relative(realRoot, requested));
    }
  }

  return { ok: true, files, skipped, truncated };
}
