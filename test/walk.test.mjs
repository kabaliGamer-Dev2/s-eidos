import assert from 'node:assert/strict';
import { mkdir, mkdtemp, rm, symlink, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import test from 'node:test';

import { collectFiles } from '../src/engine/walk.mjs';

/**
 * Build a small tree and run the collector against it.
 * @param {(root: string) => Promise<void>} build
 * @param {string[]} targets
 * @param {object} [limits]
 */
async function withTree(build, targets, limits = {}) {
  const root = await mkdtemp(join(tmpdir(), 's-eidos-walk-'));
  try {
    await build(root);
    return await collectFiles({ root, targets, limits });
  } finally {
    await rm(root, { recursive: true, force: true });
  }
}

/** @param {string} root @param {string} path @param {string} text */
const put = async (root, path, text) => {
  const full = join(root, path);
  await mkdir(join(full, '..'), { recursive: true });
  await writeFile(full, text, 'utf8');
};

test('no targets is refused, never a default directory walk', async () => {
  const result = await withTree(async () => {}, []);
  assert.equal(result.ok, false);
  assert.equal(result.error.code, 'no-targets');
});

test('extension allowlist skips files it cannot judge and says so', async () => {
  const result = await withTree(
    async (root) => {
      await put(root, 'a.js', 'const a = 1;\n');
      await put(root, 'README.md', '# readme\n');
      await put(root, 'data.bin', 'binary');
    },
    ['.'],
  );

  assert.equal(result.ok, true);
  assert.deepEqual(
    result.files.map((file) => file.path),
    ['a.js'],
  );
  assert.ok(result.skipped.some((entry) => entry.reason === 'extension' && entry.path === 'README.md'));
});

test('lockfiles, generated files and minified files are never judged', async () => {
  const minified = `const a=${'1+'.repeat(600)}1;`;
  const result = await withTree(
    async (root) => {
      await put(root, 'a.js', 'const ok = 1;\n');
      await put(root, 'package-lock.json', '{}');
      await put(root, 'gen.js', '@generated by tool\nconst g = 1;\n');
      await put(root, 'bundle.js', minified);
    },
    ['.'],
  );

  assert.equal(result.ok, true);
  const reasons = result.skipped.map((entry) => `${entry.path}:${entry.reason}`);
  assert.ok(reasons.includes('package-lock.json:lockfile'), reasons.join(', '));
  assert.ok(reasons.includes('gen.js:generated'), reasons.join(', '));
  assert.ok(reasons.includes('bundle.js:minified'), reasons.join(', '));
});

test('binary files are detected and skipped', async () => {
  const result = await withTree(
    async (root) => {
      await put(root, 'image.css', `a{color:red}\u0000`);
    },
    ['.'],
  );
  assert.equal(result.ok, true);
  assert.equal(result.files.length, 0);
  assert.ok(result.skipped.some((entry) => entry.reason === 'binary'));
});

test('dot directories are not entered', async () => {
  const result = await withTree(
    async (root) => {
      await put(root, '.github/workflow.js', 'const a = 1;\n');
      await put(root, 'src/app.js', 'const a = 1;\n');
    },
    ['.'],
  );
  assert.equal(result.ok, true);
  assert.deepEqual(
    result.files.map((file) => file.path),
    ['src/app.js'],
  );
  assert.ok(
    result.skipped.some((entry) => entry.path.includes('.github') && entry.reason === 'dot-directory'),
  );
});

test('the file cap truncates and reports truncation', async () => {
  const result = await withTree(
    async (root) => {
      for (let index = 0; index < 6; index += 1) await put(root, `f${index}.js`, 'const a = 1;\n');
    },
    ['.'],
    { maxFiles: 3 },
  );

  assert.equal(result.ok, true);
  assert.equal(result.files.length, 3);
  assert.equal(result.truncated, true);
});

test('oversized files are skipped rather than read', async () => {
  const result = await withTree(
    async (root) => {
      await put(root, 'big.js', `const a = "${'x'.repeat(500)}";\n`);
    },
    ['.'],
    { maxFileBytes: 100 },
  );
  assert.equal(result.ok, true);
  assert.equal(result.files.length, 0);
  assert.ok(result.skipped.some((entry) => entry.reason === 'too-large'));
});

test('a symlink that escapes the root is not followed', async () => {
  const outside = await mkdtemp(join(tmpdir(), 's-eidos-outside-'));
  const result = await withTree(
    async (root) => {
      await writeFile(join(outside, 'secret.js'), 'const leaked = 1;\n', 'utf8');
      try {
        await symlink(outside, join(root, 'escape'), 'dir');
      } catch {
        // Symlink creation may be refused on Windows without privilege; the test then
        // proves nothing about escacpe and is skipped by asserting only the normal file.
      }
      await put(root, 'inside.js', 'const a = 1;\n');
    },
    ['.'],
  );

  try {
    assert.equal(result.ok, true);
    // Whether or not the symlink could be created, nothing outside the root may be read.
    for (const file of result.files) assert.ok(!file.path.includes('secret.js'));
  } finally {
    await rm(outside, { recursive: true, force: true });
  }
});

test('reported paths use forward slashes so output is portable', async () => {
  const result = await withTree(
    async (root) => {
      await put(root, 'src/deep/app.js', 'const a = 1;\n');
    },
    ['.'],
  );
  assert.equal(result.ok, true);
  assert.deepEqual(
    result.files.map((file) => file.path),
    ['src/deep/app.js'],
  );
});

test('a missing target is an error, not an empty scan', async () => {
  const result = await withTree(async () => {}, ['does-not-exist']);
  assert.equal(result.ok, false);
  assert.equal(result.error.code, 'target-missing');
});
