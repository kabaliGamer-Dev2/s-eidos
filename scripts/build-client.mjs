#!/usr/bin/env node
/**
 * Build the single client module the host can load.
 *
 * There is no bundler: a client bundle must be one file in the host's combo-script format,
 * and this project has no runtime dependencies. So the build is a deterministic text
 * assembly — source parts in a fixed order, with the catalog and the locale dictionary
 * injected as JSON literals.
 *
 * `--check` regenerates in memory and fails if the committed artifact differs, so the
 * shipped bundle cannot drift from its source.
 */

import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');

const OUTPUT = join(root, 'client.js');
const PARTS = [
  join(root, 'src', 'client', 'model.mjs'),
  join(root, 'src', 'client', 'panel.part.js'),
  join(root, 'src', 'client', 'entry.part.js'),
];

/**
 * Turn an ES module that only declares things into statements the factory can hold.
 * The client model is written as a normal module so it can be unit-tested directly;
 * here its `export` keywords are the only thing that has to go.
 *
 * @param {string} source
 * @returns {string}
 */
function toFactoryStatements(source) {
  return source.replace(/^export\s+(function|const|let|class)\s/gm, '$1 ');
}

/**
 * @returns {Promise<string>} the built client module
 */
export async function build() {
  const [catalogText, localeText] = await Promise.all([
    readFile(join(root, 'rules', 'catalog.json'), 'utf8'),
    readFile(join(root, 'locale', 'en.json'), 'utf8'),
  ]);

  const catalog = JSON.parse(catalogText);
  const locale = JSON.parse(localeText);
  // `meta` is bundle display metadata for the host, not a panel string.
  delete locale.meta;

  const parts = await Promise.all(PARTS.map((path) => readFile(path, 'utf8')));
  const body = [toFactoryStatements(parts[0]), parts[1], parts[2]].join('\n');

  return [
    '// Generated by scripts/build-client.mjs from src/client/* and rules/catalog.json.',
    '// Do not edit by hand: run `npm run build`. `npm run build:check` fails on drift.',
    'window.__ModuleLoader__.load({',
    "  id: 's-eidos',",
    '  factory(require) {',
    "    const React = require('react');",
    '    const h = React.createElement;',
    `    const CATALOG = ${JSON.stringify(catalog)};`,
    `    const LOCALE = ${JSON.stringify(locale)};`,
    '',
    body,
    '  },',
    '});',
    '',
  ].join('\n');
}

/**
 * Run the build from the command line. Imported by the test suite, which calls `build()`
 * directly rather than spawning a process.
 *
 * @param {string[]} argv
 * @returns {Promise<number>} exit code
 */
export async function runCli(argv) {
  const check = argv.includes('--check');
  const built = await build();

  if (check) {
    let existing;
    try {
      existing = await readFile(OUTPUT, 'utf8');
    } catch {
      process.stderr.write('client.js is missing; run `npm run build`.\n');
      return 1;
    }
    if (existing !== built) {
      process.stderr.write('client.js is out of date with src/client and rules/catalog.json.\n');
      process.stderr.write('Run `npm run build` and commit the result.\n');
      return 1;
    }
    process.stdout.write('client.js is up to date.\n');
    return 0;
  }

  await writeFile(OUTPUT, built, 'utf8');
  process.stdout.write(`wrote ${OUTPUT} (${built.length} bytes)\n`);
  return 0;
}

const invokedDirectly =
  process.argv[1] !== undefined && pathToFileURL(process.argv[1]).href === import.meta.url;

if (invokedDirectly) {
  process.exit(await runCli(process.argv.slice(2)));
}
